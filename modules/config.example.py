# ============ 必填项 (3项) ============

# [必填] sessionid - 登录凭证
# 
# 获取步骤：
# 1. 登录 https://www.douyin.com
# 2. 按 F12 打开开发者工具
# 3. 切换到 Application 标签
# 4. 左侧 Cookies → https://www.douyin.com
# 5. 找到 sessionid，复制 Value
#
# 注意：sessionid 有有效期，失效后需重新获取
SESSION_ID = "your_sessionid_here"

# [必填] ttwid - 设备指纹
#
# 获取步骤：同上，在 Cookies 中找 ttwid
TTWID = "your_ttwid_here"

# [必填] sec_user_id - 用户标识
#
# 获取步骤：
# 1. 打开您的抖音个人主页
# 2. URL 格式：https://www.douyin.com/user/MS4wLjABAAAAxxx
# 3. 复制 user/ 后面的字符串
SEC_USER_ID = "your_sec_user_id_here"


# ============ 可选项 (使用默认值即可) ============

# 请求延时范围（秒）
# 作用：避免请求过快触发风控
# 建议：1-2秒，不建议低于1秒
REQUEST_DELAY_MIN = 1.0
REQUEST_DELAY_MAX = 2.0

# 每页数量
# 作用：单次API请求返回的视频数
# 建议：默认20，最大不超过50
PAGE_SIZE = 20

# 最大页数限制
# 作用：防止无限循环
# 默认：200页（约4000条视频）
MAX_PAGES = 200


# ============ 高级配置 ============

# User-Agent（一般不需要改）
USER_AGENT = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36"


# ============================================================
# 常见问题
# ============================================================
# 
# Q: sessionid 多久失效？
# A: 一般几小时到几天，失效后重新登录抖音获取新的即可
#
# Q: 为什么要这些信息？
# A: 抖音API需要验证您的身份，这些是您登录后的凭证
#
# Q: 这些信息安全吗？
# A: 只保存在本地，不会上传任何服务器
#    但请注意：不要把 config.py 分享给他人
#
# Q: 提示"登录已失效"怎么办？
# A: 重新登录抖音网页版，获取新的 sessionid
